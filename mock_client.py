def call_claude_mock(agent_name: str, step: str, system: str, user: str,
                     model: str = "claude-haiku-4-5-20251001",
                     max_tokens: int = 2048) -> str:
    """
    Drop-in replacement for api_client.call_claude().
    Produces realistic outputs without API calls.
    Logs identical entries to the real client so the dashboard works.
    """
    t0 = time.time()
    lat = _latency(agent_name)
    time.sleep(lat)  # simulate real latency

    # ── Dispatch to the right mock function
    if agent_name == "DataScout":
        result = _mock_data_scout()
    elif agent_name == "RatioAnalyst":
        # Extract portfolio JSON from user prompt
        try:
            start = user.index("PORTFOLIO SUMMARY:\n") + len("PORTFOLIO SUMMARY:\n")
            end   = user.index("\n\nPAYMENT HISTORY", start)
            portfolio_json = user[start:end].strip()
        except (ValueError, IndexError):
            portfolio_json = "{}"
        result = _mock_ratio_analyst(portfolio_json)
    elif agent_name == "PolicyRAG":
        try:
            start = user.index("NPL ratio:") 
            # Build minimal ratios dict from user prompt text
            ratios = json.loads(_mock_ratio_analyst("{}"))
            result = _mock_policy_rag(json.dumps(ratios))
        except Exception:
            result = _mock_policy_rag(json.dumps({"alerts":[],"npl_ratio_pct":10,"par90_ratio_pct":20,"top5_risk_loans":[]}))
    elif agent_name == "ReportWriter":
        try:
            p  = json.dumps(json.loads(open("output/portfolio_summary.json").read()))
            ra = json.dumps(json.loads(open("output/ratios.json").read()))
            po = json.dumps(json.loads(open("output/policy_context.json").read()))
        except Exception:
            p, ra, po = "{}", "{}", "{}"
        result = _mock_report_writer(p, ra, po)
    elif agent_name == "Evaluator" and "iteration_1" in step:
        result = _mock_evaluator_v1()
    elif agent_name == "Evaluator":
        result = _mock_evaluator_v2()
    elif agent_name == "SingleAgent":
        result = _mock_single_agent()
    else:
        result = json.dumps({"mock": True, "agent": agent_name, "step": step})

    # ── Log exactly like the real client (dashboard reads these logs)
    log_call(
        agent_name=agent_name,
        step=step,
        prompt_tokens=len(user.split()) * 4 // 3,    # realistic estimate
        completion_tokens=len(result.split()) * 4 // 3,
        latency_s=lat,
        success=True,
        notes="MOCK_MODE"
    )

    return result
